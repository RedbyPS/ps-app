// "Copy for AI" (Settings, AI task API). The developer: "a copy to clipboard button to copy a bunch of text to just paste to AI
// like Claude Code or GPT Codex so an AI can just read through it all and understand everything and carry it out."
// One plain text an AI that has never seen PS can work from alone: where the API is, the key, every endpoint with a
// curl example and its JSON, what each switch allows (and which are on now), the errors, and how the AI Inbox works.
// The key is never in this page: the text carries KEY_SLOT and PS on the Mac puts the key in as it copies
// (ps-mac TaskApi.swift). Pure: no React, no DOM.
import { API_PORT, BATCH_MAX, LIST_LIMIT_DEF, LIST_LIMIT_MAX, NOTES_MAX, SCOPES, TITLE_MAX, type Scopes } from "./taskapi.ts";
